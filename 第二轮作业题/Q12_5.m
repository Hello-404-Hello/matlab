a=readmatrix('Temp2.xlsx');
n=size(a,1);
f=fft(a-mean(a),2*n);
d=f(:,2).*conj(f(:,1));
f=real(ifft(d./max(abs(d),eps)));
k=-50:50;
[~,i]=max(f(mod(k,2*n)+1));
s=k(i);
disp([1+(s<0),s/100,5/abs(s)])
figure
t=(0:n-1)/100;
tiledlayout(2,1)
nexttile
plot(t,a(:,1),'-',t,a(:,2),':')
legend('1','2')
ylabel('温度')
nexttile
stem(k,f(mod(k,2*n)+1))
xlabel('滞后样本')
